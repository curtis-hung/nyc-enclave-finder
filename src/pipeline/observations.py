"""Machine-generated, numbers-first digests (§13.8) and the enrichment report for the M7 checkpoint.

docs/OBSERVATIONS.md: descriptive only — no explanations, no categories.
docs/CUISINES.md: enrichment match rates, tag counts, conflicts, tag coverage, spot-check samples.
"""

from __future__ import annotations

import json
import math
import random
import statistics
from collections import Counter, defaultdict
from typing import Any

from pipeline.config import load_config
from pipeline.paths import LOG_DIR, REPO_ROOT, WEB_DATA_DIR

DOCS = REPO_ROOT / "docs"


def _j(path: str) -> Any:
    return json.loads((WEB_DATA_DIR / path).read_text(encoding="utf-8"))


def _fmt(x: float | None, nd: int = 2) -> str:
    return "—" if x is None else f"{x:,.{nd}f}"


def write_observations() -> None:
    cfg = load_config()
    groups = _j("groups.json")["groups"]
    meta = _j("meta.json")
    presets = list(cfg.presets["presets"])
    default = cfg.presets["default_preset"]
    cuis = {n["id"]: n["name"] for n in _j("cuisines.json")["nodes"]}
    out: list[str] = []
    w = out.append
    w("# Observations digest")
    w("")
    w("_Machine-generated by `uv run pipeline report` from the built data. Numbers only: descriptive, "
      "no explanations and no categories. Default dimension of each group unless stated._")
    w("")

    # 1. gaps by group (exact pairings, default preset, default dimension)
    w(f"## 1. Nearest-enclave distance by group ({default} preset, exact cuisine pairings)")
    w("")
    w("Polygon distance (0 = touching/overlapping) and signed edge distance from the cluster center "
      "(negative = inside the nearest enclave by that much).")
    w("")
    w("| Group | Clusters | Min (mi) | Median (mi) | Max (mi) | Median edge (mi) | Clusters with no enclave |")
    w("|---|---|---|---|---|---|---|")
    gap_rows = []
    for gid, g in groups.items():
        gp = WEB_DATA_DIR / "gaps" / f"{gid}.json"
        if not gp.exists():
            continue
        data = json.loads(gp.read_text(encoding="utf-8"))
        rows = [r for r in data["rows"].get(default, {}).get(g["default_dimension"], []) if r["kind"] == "exact"]
        if not rows:
            continue
        d = [r["d"][0] for r in rows if r["d"][0] is not None]
        e = [r["edge"] for r in rows if r.get("edge") is not None]
        gap_rows.append((g["name"], len(rows), min(d) if d else None, statistics.median(d) if d else None,
                         max(d) if d else None, statistics.median(e) if e else None, sum(1 for r in rows if r["d"][0] is None)))
    for name, n, mn, md, mx, me, nul in sorted(gap_rows, key=lambda r: (-(r[4] or -1), r[0])):
        w(f"| {name} | {n} | {_fmt(mn)} | {_fmt(md)} | {_fmt(mx)} | {_fmt(me)} | {nul} |")
    w("")

    # 2. groups with multiple enclaves
    w(f"## 2. Groups with more than one enclave ({default} preset)")
    w("")
    w("| Group | Enclaves | Largest enclave residents | Share of group's citywide residents in enclaves |")
    w("|---|---|---|---|")
    multi = []
    for gid, g in groups.items():
        st = _j(f"enclaves/{gid}.json")["stats"].get(g["default_dimension"], {}).get(default)
        if st and len(st["items"]) > 1:
            items = st["items"]
            multi.append((g["name"], len(items), items[0]["pop"], sum(i["share"] or 0 for i in items)))
    for name, n, big, sh in sorted(multi, key=lambda r: (-r[1], r[0])):
        w(f"| {name} | {n} | {big:,} | {sh:.1%} |")
    w("")

    # 3. NTAs with many over-represented groups
    w("## 3. Neighborhoods with the most over-represented groups")
    w("")
    w("Distinct finest-level groups with LQ > 1 and a usable estimate, across race, Hispanic origin, Asian "
      "group, ancestry and birthplace (language excluded).")
    w("")
    wh = _j("whoshere/nta.json")
    counts = []
    for i, u in enumerate(wh["units"]):
        ids = {wh["candidates"][d][r[0]]["id"] for d in u if d != "language" for r in u[d]["lq"]}
        counts.append((len(ids), meta["ntas"][i]["name"], meta["ntas"][i]["boro"]))
    boro_name = {b["code"]: b["name"] for b in meta["boroughs"]}
    w("| NTA | Borough | Over-represented groups (listed, max 10 per dimension) |")
    w("|---|---|---|")
    for n, name, b in sorted(counts, key=lambda x: (-x[0], x[1]))[:15]:
        w(f"| {name} | {boro_name[b]} | {n} |")
    w("")

    # 4. high-cuisine-LQ clusters
    w(f"## 4. Clusters with the highest cuisine LQ ({default} preset, at least 8 restaurants)")
    w("")
    w("| Cuisine | Cluster | Restaurants | Independent | Cuisine LQ | Cuisine share of catchment |")
    w("|---|---|---|---|---|---|")
    allc = []
    for f in (WEB_DATA_DIR / "clusters").glob("*.json"):
        data = json.loads(f.read_text(encoding="utf-8"))
        for k, c in enumerate(data["stats"].get(default, [])):
            if c["restaurants"] >= 8:
                allc.append((c["lq"], cuis.get(data["node"], data["node"]), k + 1, c))
    for lq, name, k, c in sorted(allc, key=lambda x: (-x[0], x[1], x[2]))[:20]:
        w(f"| {name} | #{k} | {c['restaurants']} | {c['independent']} | {lq:.2f} | {c['share']:.1%} |")
    w("")

    # 5. diversity
    w("## 5. Neighborhoods with the highest residential diversity")
    w("")
    w("Diversity = normalized Shannon entropy of the eight race/Hispanic-origin categories (B03002): "
      "−Σ p·ln p / ln 8, from 0 (one category) to 1 (all eight equal). NTAs with at least 1,000 residents.")
    w("")
    race_groups = [gid for gid, g in groups.items() if "race" in g["dims"] and not g["dims"]["race"]["derived"]]
    den = _j("denominators.json")["race"]["nta"]
    ests = {gid: _j(f"demo/{gid}/race.json")["nta"]["e"] for gid in race_groups}
    div = []
    for i in range(len(den)):
        tot = den[i] or 0
        if tot < 1000:
            continue
        ps = [(ests[g][i] or 0) / tot for g in race_groups]
        h = -sum(p * math.log(p) for p in ps if p > 0) / math.log(len(race_groups))
        div.append((h, meta["ntas"][i]["name"], meta["ntas"][i]["boro"], tot))
    w("| NTA | Borough | Diversity | Residents |")
    w("|---|---|---|---|")
    for h, name, b, tot in sorted(div, key=lambda x: (-x[0], x[1]))[:10]:
        w(f"| {name} | {boro_name[b]} | {h:.3f} | {tot:,} |")
    w("")

    # 6. preset sensitivity
    w("## 6. How results shift between presets")
    w("")
    log = json.loads((LOG_DIR / "build_log.json").read_text(encoding="utf-8"))
    enc_n = Counter()
    for gid, g in groups.items():
        st = _j(f"enclaves/{gid}.json")["stats"].get(g["default_dimension"], {})
        for p in presets:
            enc_n[p] += len(st.get(p, {}).get("items", []))
    cl_n = Counter()
    for v in log["clusters"].values():
        for p in presets:
            cl_n[p] += v.get(p, 0)
    dists: dict[str, list[float]] = defaultdict(list)
    edges: dict[str, list[float]] = defaultdict(list)
    zero: Counter = Counter()
    nul: Counter = Counter()
    tot_rows: Counter = Counter()
    for gid, g in groups.items():
        gp = WEB_DATA_DIR / "gaps" / f"{gid}.json"
        if not gp.exists():
            continue
        data = json.loads(gp.read_text(encoding="utf-8"))
        for p in presets:
            for r in data["rows"].get(p, {}).get(g["default_dimension"], []):
                if r["kind"] != "exact":
                    continue
                tot_rows[p] += 1
                if r["d"][0] is None:
                    nul[p] += 1
                else:
                    dists[p].append(r["d"][0])
                    if r.get("edge") is not None:
                        edges[p].append(r["edge"])
                    zero[p] += r["d"][0] == 0
    w("| Measure | " + " | ".join(presets) + " |")
    w("|---|" + "---|" * len(presets))
    w("| Enclaves (default dimensions, all groups) | " + " | ".join(f"{enc_n[p]:,}" for p in presets) + " |")
    w("| Restaurant clusters (all paired cuisines) | " + " | ".join(f"{cl_n[p]:,}" for p in presets) + " |")
    w("| Exact-pairing cluster rows | " + " | ".join(f"{tot_rows[p]:,}" for p in presets) + " |")
    w("| Median nearest-enclave distance (mi) | " + " | ".join(_fmt(statistics.median(dists[p]) if dists[p] else None) for p in presets) + " |")
    w("| Median signed edge distance (mi; negative = inside) | " + " | ".join(_fmt(statistics.median(edges[p]) if edges[p] else None) for p in presets) + " |")
    w("| Rows with distance 0 | " + " | ".join(f"{zero[p] / tot_rows[p]:.1%}" if tot_rows[p] else "—" for p in presets) + " |")
    w("| Rows with no enclave (null) | " + " | ".join(f"{nul[p]:,}" for p in presets) + " |")
    w("")
    w("Preset parameters:")
    w("")
    for p, d in cfg.presets["presets"].items():
        w(f"- **{d['label']}** — enclave: {d['enclave']}; cluster: {d['cluster']}")
    (DOCS / "OBSERVATIONS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {DOCS / 'OBSERVATIONS.md'}")


def write_cuisines_report() -> None:
    cfg = load_config()
    cg = cfg.cuisines
    log = json.loads((LOG_DIR / "build_log.json").read_text(encoding="utf-8"))
    rd = log["restaurants"]
    pts = _j("restaurants/points.json")
    nodes = _j("cuisines.json")["nodes"]
    out: list[str] = []
    w = out.append
    w("# Restaurant labels and enrichment")
    w("")
    w("_Generated by `uv run pipeline report`. Labels come only from restaurant data (§2.3)._")
    w("")
    w("## Backbone")
    w("")
    for k in ("raw_rows", "unique_camis", "dropped_missing_or_invalid_coordinates", "filtered_inactive",
              "dropped_outside_nyc_tracts", "retained_establishments", "uninspected_retained",
              "multi_location_flagged", "multi_location_businesses", "analysis_population"):
        w(f"- {k.replace('_', ' ')}: {rd[k]:,}")
    w(f"- inactive rule: {rd['inactive_rule']}")
    w("")
    m = rd["matching"]
    w("## Enrichment match rates")
    w("")
    w("| Source | External places | Matched to DOHMH | Share of establishments matched |")
    w("|---|---|---|---|")
    w(f"| OpenStreetMap | {m['osm']['external_places']:,} ({m['osm']['with_cuisine']:,} with cuisine=) | {m['osm']['matched']:,} | {m['osm']['match_rate']:.1%} |")
    w(f"| Overture Places | {m['overture']['external_places']:,} | {m['overture']['matched']:,} | {m['overture']['match_rate']:.1%} |")
    w(f"| Name keywords | — | {m['keyword']['keyword_hits']:,} hits | — |")
    w("")
    w("Match rate by DOHMH primary label (top 25 by count):")
    w("")
    w("| Primary | Establishments | OSM | Overture |")
    w("|---|---|---|---|")
    for r in m["rate_by_primary"][:25]:
        w(f"| {cg.nodes[r['primary']].name} | {r['n']:,} | {r['_osm']:.0%} | {r['_ov']:.0%} |")
    w("")
    w("## Tags and conflicts")
    w("")
    tbc = rd["tags_by_confidence"]
    w(f"- tags by confidence: high {tbc.get('high', 0):,} · medium {tbc.get('medium', 0):,} · low {tbc.get('low', 0):,}")
    w(f"- restaurants with at least one tag: {rd['restaurants_with_tags']:,}")
    w(f"- conflicts: {rd['conflicts']:,} on {rd['restaurants_with_conflicts']:,} restaurants (never used for filtering, clustering or LQ)")
    w(f"- unmapped external labels (counted, mapped to root): {rd['unmapped_external_labels']}")
    w("")
    w("### Tag coverage by bucket (citywide, analysis population)")
    w("")
    w("Share of restaurants whose DOHMH primary is the bucket that carry any medium+ tag.")
    w("")
    w("| Bucket primary | Restaurants | With medium+ tag | Coverage |")
    w("|---|---|---|---|")
    by = Counter()
    tagged = Counter()
    for i in range(pts["n"]):
        if not pts["flags"][i] & 4:
            continue
        p = nodes[pts["primary"][i]]
        if p["kind"] != "bucket":
            continue
        by[p["id"]] += 1
        if any(c >= 2 for _, c in pts["tags"].get(str(i), [])):
            tagged[p["id"]] += 1
    for b, n in by.most_common():
        w(f"| {cg.nodes[b].name} | {n:,} | {tagged[b]:,} | {tagged[b] / n:.1%} |")
    w("")
    # samples
    details: dict[str, Any] = {}
    for f in sorted((WEB_DATA_DIR / "restaurants" / "details").glob("*.json")):
        details.update(json.loads(f.read_text(encoding="utf-8")))
    rng = random.Random(20261008)
    tagged_ids = sorted((k for k, d in details.items() if d["tags"]), key=int)
    conflict_ids = sorted((k for k, d in details.items() if d["conflicts"]), key=int)
    w("## Spot-check sample: 20 tagged restaurants (seeded random)")
    w("")
    w("| Restaurant | DOHMH category | Tags (confidence: sources) |")
    w("|---|---|---|")
    for k in rng.sample(tagged_ids, min(20, len(tagged_ids))):
        d = details[k]
        tags = "; ".join(f"**{cg.nodes[t['label']].name}** ({t['confidence']}: " + ", ".join(s["evidence"] for s in t["sources"]) + ")" for t in d["tags"])
        w(f"| {d['name']} ({d['boro']}) | {d['cuisine_dohmh']} | {tags} |")
    w("")
    w("## Spot-check sample: 10 conflicts (seeded random)")
    w("")
    w("| Restaurant | DOHMH category | Other sources say |")
    w("|---|---|---|")
    for k in rng.sample(conflict_ids, min(10, len(conflict_ids))):
        d = details[k]
        cs = "; ".join(f"{cg.nodes[c['label']].name} ({c['evidence']})" for c in d["conflicts"])
        w(f"| {d['name']} ({d['boro']}) | {d['cuisine_dohmh']} | {cs} |")
    (DOCS / "CUISINES.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {DOCS / 'CUISINES.md'}")
