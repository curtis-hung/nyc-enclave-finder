"""`uv run pipeline report`: human-readable taxonomy/crosswalk report and review figures.

Writes docs/TAXONOMY.md (generated; do not edit by hand) and docs/figures/*.png.
"""

from __future__ import annotations

import json
from collections import Counter
from pipeline.config import Config, load_config
from pipeline.fetch.common import existing_snapshot, load_manifest
from pipeline.paths import LOG_DIR, REPO_ROOT, WEB_DATA_DIR

DOCS = REPO_ROOT / "docs"
STATE_NAMES = ["reliable", "caution", "suppressed", "unavailable", "zero"]


def dohmh_cuisine_counts() -> Counter:
    import pandas as pd

    entry = existing_snapshot(load_manifest(), "dohmh")
    if not entry:
        return Counter()
    df = pd.read_csv(REPO_ROOT / entry["files"][0]["path"], usecols=["CAMIS", "CUISINE DESCRIPTION"], dtype=str)
    per = df.dropna(subset=["CUISINE DESCRIPTION"]).drop_duplicates("CAMIS")
    c = Counter(per["CUISINE DESCRIPTION"])
    c["(blank)"] = int(df.CAMIS.nunique() - per.CAMIS.nunique())
    return c


def _tree_lines(cfg: Config, groups_json: dict, log: dict) -> list[str]:
    lines = []

    def walk(gid: str, depth: int) -> None:
        g = cfg.groups[gid]
        gj = groups_json["groups"][gid]
        dims = []
        for dim_id, dm in gj["dims"].items():
            star = "**" if dim_id == g.default_dimension else ""
            flag = " (bucket)" if dm["bucket"] else (" (sum)" if dm["derived"] else "")
            lvl = "" if dm["level"] == "tract" else ", NTA"
            dims.append(f"{star}{dim_id}{star}{flag} {dm['city']['e']:,}{lvl}")
        lines.append(f"{'  ' * depth}- **{g.name}** `{gid}` — " + "; ".join(dims))
        for c in g.children:
            walk(c, depth + 1)

    for r in groups_json["roots"]:
        walk(r, 0)
    return lines


def write_taxonomy(cfg: Config) -> None:
    groups_json = json.loads((WEB_DATA_DIR / "groups.json").read_text(encoding="utf-8"))
    meta = json.loads((WEB_DATA_DIR / "meta.json").read_text(encoding="utf-8"))
    log = json.loads((LOG_DIR / "build_log.json").read_text(encoding="utf-8"))
    acs_dir = REPO_ROOT / "data" / "raw" / "acs5"
    out: list[str] = []
    w = out.append
    w("# Taxonomy, crosswalk and data granularity")
    w("")
    w("_Generated by `uv run pipeline report` from `config/*.yaml` and the pinned snapshots. Do not edit._")
    w("")
    w(f"ACS 5-year vintage: **{meta['acs_vintage']}**. Tracts: {meta['levels']['tract']:,}; "
      f"NTAs: {meta['levels']['nta']}; boroughs: {meta['levels']['boro']}.")
    w("")
    w("## Dimensions")
    w("")
    w("| Dimension | Table | Categories at tract level | Numerator universe | Share of | Summable |")
    w("|---|---|---|---|---|---|")
    for d in cfg.dimensions.values():
        vj = json.loads(next(acs_dir.glob(f"*/{d.table}_variables.json")).read_text(encoding="utf-8"))
        n_leaf = sum(1 for v in vj.values() if not v["label"].endswith(":"))
        gran = f"{n_leaf} leaf lines ({len(vj)} incl. subtotals)"
        if d.table == "C16001":
            gran = "12 language categories (each split by English ability)"
        w(f"| {d.name} | {d.table} | {gran} | {d.numerator_universe} | "
          f"{d.share_of} | {'yes' if d.summable else 'no (overlapping)'} |")
    w("")
    w("### Language granularity at tract level (C16001)")
    w("")
    vj = json.loads(next(acs_dir.glob("*/C16001_variables.json")).read_text(encoding="utf-8"))
    cats = [v["label"].split("!!")[-1].rstrip(":") for k, v in vj.items()
            if v["label"].count("!!") == 2 and v["label"].endswith(":")]
    w("The detailed language table B16001 is **not published at tract level** (every tract value is null). "
      f"C16001 has {len(cats)} language categories plus 'Speak only English':")
    w("")
    for c in cats:
        w(f"- {c}")
    w("")
    w("So Yiddish sits inside *German or other West Germanic*; Russian inside *Russian, Polish, or other "
      "Slavic*; Thai and Japanese inside *Other Asian and Pacific Island languages*; Bengali, Hindi, Urdu, "
      "Nepali and Punjabi inside *Other Indo-European languages* (together with Italian, Greek, Portuguese, "
      "Persian and others). Language mappings are flagged as buckets except "
      "Korean and Vietnamese (and Spanish/Chinese/Tagalog/Arabic, which are flagged because they cover several "
      "origins).")
    w("")
    w("## Group hierarchy and crosswalk")
    w("")
    w("Bold dimension = `default_dimension`. Numbers are citywide estimates in that dimension. "
      "`(sum)` = broad group summed from children within one dimension; `(bucket)` = the source category is "
      "broader than the group; `NTA` = too sparse at tract level, so shown and analysed at NTA level "
      "(less than half of the group's residents sit in tracts with a reliable/caution value).")
    w("")
    out.extend(_tree_lines(cfg, groups_json, log))
    w("")
    w("## Default dimension per group, with rationale")
    w("")
    w("| Group | Default | Level | Rationale |")
    w("|---|---|---|---|")
    for gid, g in cfg.groups.items():
        dm = groups_json["groups"][gid]["dims"][g.default_dimension]
        w(f"| {g.name} | {g.default_dimension} | {dm['level']} | {g.rationale} |")
    w("")
    w("## Source buckets and partial sums")
    w("")
    for gid, gj in groups_json["groups"].items():
        for dim_id, dm in gj["dims"].items():
            if dm["bucket"]:
                w(f"- {gj['name']} / {dim_id}: bucket — {dm['bucket']} ({', '.join(dm['labels'])})")
            if dm["missing_from_sum"]:
                w(f"- {gj['name']} / {dim_id}: sum excludes {', '.join(dm['missing_from_sum'])} "
                  "(no exact category in this dimension)")
    w("")
    w("## Cuisine pairings")
    w("")
    w("| Group | Exact | Bucket |")
    w("|---|---|---|")
    for gid, g in cfg.groups.items():
        ex = [cfg.cuisines.nodes[c].name for c, k in g.cuisines.items() if k == "exact"]
        bu = [cfg.cuisines.nodes[c].name for c, k in g.cuisines.items() if k == "bucket"]
        if ex or bu:
            w(f"| {g.name} | {', '.join(ex)} | {', '.join(bu)} |")
    no_pair = [g.name for g in cfg.groups.values() if not g.cuisines]
    w("")
    w(f"Groups with no paired cuisine: {', '.join(no_pair)}.")
    w("")
    w("## DOHMH cuisine values (enumerated from the snapshot)")
    w("")
    counts = dohmh_cuisine_counts()
    dmap = cfg.cuisines.dohmh_map()
    w("| DOHMH value | Establishments (unique CAMIS) | Hierarchy node | Kind |")
    w("|---|---|---|---|")
    for v, n in counts.most_common():
        nid = dmap.get(v, "root" if v == "(blank)" else "**UNMAPPED**")
        kind = cfg.cuisines.nodes[nid].kind if nid in cfg.cuisines.nodes else ""
        w(f"| {v} | {n:,} | {nid} | {kind} |")
    unmapped = [v for v in counts if v != "(blank)" and v not in dmap]
    w("")
    w(f"Unmapped values: {unmapped if unmapped else 'none'}.")
    w("")
    w("## Plausibility checks (warn-only, §13.4)")
    w("")
    w("| Check | NTA containing the place | Rank by LQ | LQ | Top 3 NTAs | Result |")
    w("|---|---|---|---|---|---|")
    for p in log["plausibility"]:
        top = "; ".join(f"{t['nta']} ({t['lq']})" for t in p["top_3"])
        w(f"| {p['description']} | {p['nta_name']} | {p['nta_rank']} of {p['ntas_ranked']} | {p['nta_lq']} | "
          f"{top} | {'pass' if p['passed'] else 'WARN'} |")
    w("")
    w("Korean-cuisine concentration around W 32nd St is checked at M6 (restaurants).")
    w("")
    w("## Data states at tract level (default dimension)")
    w("")
    w("| Group | Dimension | " + " | ".join(STATE_NAMES) + " | usable share |")
    w("|---|---|" + "---|" * 6)
    for gid, g in cfg.groups.items():
        gd = log["group_dims"][gid][g.default_dimension]
        w(f"| {g.name} | {g.default_dimension} | " + " | ".join(str(x) for x in gd["states_tract"])
          + f" | {gd['usable_share_tract']:.0%} |")
    (DOCS / "TAXONOMY.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {DOCS / 'TAXONOMY.md'}")


def write_figures(cfg: Config, groups: list[str]) -> None:
    import geopandas as gpd
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import numpy as np
    from matplotlib.colors import BoundaryNorm, ListedColormap

    figdir = DOCS / "figures"
    figdir.mkdir(parents=True, exist_ok=True)
    tracts = gpd.read_file(WEB_DATA_DIR / "geo" / "tracts.json")
    ntas = gpd.read_file(WEB_DATA_DIR / "geo" / "ntas.json")
    gj = json.loads((WEB_DATA_DIR / "groups.json").read_text(encoding="utf-8"))
    # same scale as the web map (web/src/scales.ts): two greys below 1, 8 blues above
    bounds = [0, 0.5, 1, 1.5, 2, 3, 4, 6, 10, 20, 1e9]
    cmap = ListedColormap(["#f1f0ee", "#e0e0dd", "#87b4f0", "#689de5", "#4987d9", "#2970c9", "#065bb5", "#004799", "#003479", "#002455"])
    norm = BoundaryNorm(bounds, cmap.N)
    n = len(groups)
    cols = 3
    rows = int(np.ceil(n / cols))
    fig, axes = plt.subplots(rows, cols, figsize=(cols * 5, rows * 5.2))
    for ax, gid in zip(np.ravel(axes), groups):
        g = gj["groups"][gid]
        dim = g["default_dimension"]
        lvl = g["dims"][dim]["level"]
        data = json.loads((WEB_DATA_DIR / "demo" / gid / f"{dim}.json").read_text(encoding="utf-8"))[lvl]
        geo = (tracts if lvl == "tract" else ntas).copy()
        geo["lq"] = [data["lq"][i] for i in geo["i"]]
        geo["st"] = [data["st"][i] for i in geo["i"]]
        geo[geo.st == 3].plot(ax=ax, color="#ffffff", edgecolor="#cccccc", linewidth=0.2)  # unavailable
        geo[geo.st == 2].plot(ax=ax, color="#d9d9d9", hatch="////", edgecolor="#bbbbbb", linewidth=0.2)  # suppressed
        geo[geo.st == 4].plot(ax=ax, color="#fafafa", edgecolor="#e0e0e0", linewidth=0.2)  # zero
        v = geo[geo.st.isin([0, 1])]
        v.plot(ax=ax, column="lq", cmap=cmap, norm=norm, linewidth=0)
        v[v.st == 1].plot(ax=ax, facecolor="none", edgecolor="#555555", hatch="...", linewidth=0)
        ax.set_title(f"{g['name']} — {dim}, LQ by {lvl}", fontsize=10)
        ax.set_axis_off()
    for ax in np.ravel(axes)[n:]:
        ax.set_axis_off()
    sm = plt.cm.ScalarMappable(cmap=cmap, norm=norm)
    cb = fig.colorbar(sm, ax=axes, shrink=0.5, location="right", ticks=bounds[:-1])
    cb.set_label("Location quotient (white = no residents; grey hatched = suppressed; dotted = caution)")
    path = figdir / "m2_default_dimension_lq.png"
    fig.savefig(path, dpi=80, bbox_inches="tight")
    plt.close(fig)
    print(f"wrote {path}")


def run_report() -> int:
    from pipeline.observations import write_cuisines_report, write_observations

    cfg = load_config()
    write_taxonomy(cfg)
    write_observations()
    write_cuisines_report()
    write_figures(cfg, ["thai", "dominican", "chinese", "korean", "jamaican", "bangladeshi",
                        "ecuadorian", "russian", "nepali"])
    return 0

